#!/usr/bin/python3
"""Emit a shell script that restores file/directory ownership and modes.

Usage: metadata-fix.py <before> <after>
Each input line: "<octal mode> <uid> <gid> <path>" (find -printf '%m %U %G %p').
Paths present in only one snapshot are ignored.
"""

import shlex
import sys


def load(path):
    entries = {}
    with open(path, encoding="utf-8", errors="surrogateescape") as fh:
        for line in fh:
            mode, uid, gid, p = line.rstrip("\n").split(" ", 3)
            entries[p] = (mode, uid, gid)
    return entries


def main(before_path, after_path):
    before, after = load(before_path), load(after_path)
    print("# generated by scripts/metadata-fix.py")
    for p in sorted(before.keys() & after.keys()):
        (bm, bu, bg), (am, au, ag) = before[p], after[p]
        q = shlex.quote(p)
        if (bu, bg) != (au, ag):
            print(f"chown -h {bu}:{bg} {q}")
        if bm != am:
            print(f"chmod {bm} {q}")
    return 0


if __name__ == "__main__":
    sys.exit(main(*sys.argv[1:3]))
